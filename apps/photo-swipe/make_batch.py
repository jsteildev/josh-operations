#!/usr/bin/env python3
"""Build a self-contained Photo Swipe batch from a folder of images.

Usage:
    python3 make_batch.py <source_dir> <output_dir> --batch-id b1 [--password secret]

Reads images (jpg/jpeg/png/heic/heif), resizes so the long edge is at most
1600px, converts to JPEG quality 82, and writes them as 001.jpg, 002.jpg, ...
into <output_dir>/photos/ in filename-sorted order. Copies the app files into
<output_dir>/, writes manifest.json and a config.js with the batch id and
password, then prints a summary.

HEIC/HEIF needs the pillow-heif package (pip install pillow-heif). Without it,
HEIC files are skipped with a warning.
"""

import argparse
import json
import shutil
import sys
from pathlib import Path

try:
    from PIL import Image, ImageOps
except ImportError:
    sys.exit("Pillow is required: pip install pillow")

try:
    from pillow_heif import register_heif_opener

    register_heif_opener()
    HEIF_OK = True
except ImportError:
    HEIF_OK = False

APP_DIR = Path(__file__).resolve().parent
APP_FILES = ["index.html", "styles.css", "app.js"]
IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".heic", ".heif"}
LONG_EDGE = 1600
JPEG_QUALITY = 82


def process_image(src: Path, dst: Path) -> bool:
    """Resize/convert one image. Returns True on success, False on failure."""
    try:
        with Image.open(src) as img:
            img = ImageOps.exif_transpose(img).convert("RGB")
            w, h = img.size
            scale = min(1.0, LONG_EDGE / max(w, h))
            if scale < 1.0:
                img = img.resize((round(w * scale), round(h * scale)), Image.LANCZOS)
            img.save(dst, "JPEG", quality=JPEG_QUALITY)
        return True
    except Exception as exc:  # noqa: BLE001 - we want a per-file warning, not a crash
        print(f"  warning: skipping {src.name} ({exc})")
        return False


def main() -> int:
    parser = argparse.ArgumentParser(description="Build a Photo Swipe batch.")
    parser.add_argument("source_dir", help="Folder of source images")
    parser.add_argument("output_dir", help="Folder to write the batch app into")
    parser.add_argument("--batch-id", required=True, help="Batch id, e.g. b1")
    parser.add_argument("--password", default="changeme", help="Gate password for this batch")
    args = parser.parse_args()

    if ":" in args.batch_id:
        sys.exit("error: --batch-id must not contain a colon")

    src_dir = Path(args.source_dir)
    out_dir = Path(args.output_dir)
    if not src_dir.is_dir():
        sys.exit(f"error: source dir not found: {src_dir}")

    photos_dir = out_dir / "photos"
    photos_dir.mkdir(parents=True, exist_ok=True)

    candidates = sorted(
        (p for p in src_dir.iterdir() if p.is_file() and p.suffix.lower() in IMAGE_EXTS),
        key=lambda p: p.name.lower(),
    )
    if not HEIF_OK and any(p.suffix.lower() in {".heic", ".heif"} for p in candidates):
        print("  note: pillow-heif is not installed; HEIC/HEIF files will be skipped "
              "(pip install pillow-heif to include them)")

    count_in = len(candidates)
    written = []
    for i, src in enumerate(candidates, start=1):
        dst = photos_dir / f"{i:03d}.jpg"
        if process_image(src, dst):
            written.append(dst.name)
        # on failure the numbered slot is simply skipped; order of the
        # survivors still follows the sorted source order

    # Renumber survivors so there are no gaps (001.jpg, 002.jpg, ...).
    final_names = []
    for i, name in enumerate(written, start=1):
        new_name = f"{i:03d}.jpg"
        if name != new_name:
            (photos_dir / name).rename(photos_dir / new_name)
        final_names.append(new_name)

    for fname in APP_FILES:
        src = APP_DIR / fname
        if not src.exists():
            sys.exit(f"error: app file missing next to make_batch.py: {fname}")
        shutil.copy2(src, out_dir / fname)

    manifest = {"batch_id": args.batch_id, "photos": final_names}
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")

    config_js = (
        "/* Generated by make_batch.py. This gate is casual obfuscation, not real security. */\n"
        f"window.SWIPE_CONFIG = {{\n"
        f'  password: {json.dumps(args.password)},\n'
        f'  batchId: {json.dumps(args.batch_id)}\n'
        "};\n"
    )
    (out_dir / "config.js").write_text(config_js)

    print(f"batch id : {args.batch_id}")
    print(f"in       : {count_in} image(s) found in {src_dir}")
    print(f"out      : {len(final_names)} photo(s) written to {photos_dir}")
    print(f"dir      : {out_dir}")
    print("serve with: python3 -m http.server --directory " + str(out_dir) + " 8000")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
